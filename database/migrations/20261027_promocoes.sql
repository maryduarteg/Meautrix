-- Executar antes de iniciar a versão com Gestão de Promoções.
-- Transacional: dados incompatíveis interrompem a alteração sem excluir registros.
BEGIN;

CREATE TABLE IF NOT EXISTS public.promocoes (
    prom_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    prom_titulo VARCHAR(60) NOT NULL,
    prom_mensagem VARCHAR(100) NOT NULL,
    prom_data_minima DATE NOT NULL,
    prom_data_maxima DATE NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT promocoes_pk PRIMARY KEY (prom_id)
);

ALTER TABLE public.promocoes
    ADD COLUMN IF NOT EXISTS prom_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    ADD COLUMN IF NOT EXISTS prom_titulo VARCHAR(60),
    ADD COLUMN IF NOT EXISTS prom_mensagem VARCHAR(100),
    ADD COLUMN IF NOT EXISTS prom_data_minima DATE,
    ADD COLUMN IF NOT EXISTS prom_data_maxima DATE,
    ADD COLUMN IF NOT EXISTS created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP;

-- Recusa textos longos antes da conversão de tipo, evitando truncamento.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM public.promocoes
        WHERE length(prom_titulo) > 60 OR length(prom_mensagem) > 100) THEN
        RAISE EXCEPTION 'Existem títulos com mais de 60 ou mensagens com mais de 100 caracteres. Revise os registros.';
    END IF;
END $$;

ALTER TABLE public.promocoes
    ALTER COLUMN prom_id TYPE INTEGER,
    ALTER COLUMN prom_titulo TYPE VARCHAR(60),
    ALTER COLUMN prom_titulo SET NOT NULL,
    ALTER COLUMN prom_mensagem TYPE VARCHAR(100),
    ALTER COLUMN prom_mensagem SET NOT NULL,
    ALTER COLUMN prom_data_minima TYPE DATE,
    ALTER COLUMN prom_data_minima SET NOT NULL,
    ALTER COLUMN prom_data_maxima TYPE DATE,
    ALTER COLUMN prom_data_maxima SET NOT NULL,
    ALTER COLUMN created_at TYPE TIMESTAMP WITH TIME ZONE,
    ALTER COLUMN created_at SET DEFAULT CURRENT_TIMESTAMP;

DO $$
DECLARE
    identidade "char";
    sequencia text;
    maior_id bigint;
    ultimo_id bigint;
BEGIN
    SELECT attidentity INTO identidade FROM pg_attribute
        WHERE attrelid = 'public.promocoes'::regclass AND attname = 'prom_id';
    IF identidade = '' THEN
        -- Desassocia a sequência SERIAL antiga sem removê-la.
        sequencia := pg_get_serial_sequence('public.promocoes', 'prom_id');
        IF sequencia IS NOT NULL THEN
            ultimo_id := pg_sequence_last_value(sequencia::regclass);
            EXECUTE format('ALTER SEQUENCE %s OWNED BY NONE', sequencia::regclass);
        END IF;
        ALTER TABLE public.promocoes ALTER COLUMN prom_id DROP DEFAULT;
        ALTER TABLE public.promocoes ALTER COLUMN prom_id SET NOT NULL;
        ALTER TABLE public.promocoes ALTER COLUMN prom_id ADD GENERATED BY DEFAULT AS IDENTITY;
    ELSE
        ALTER TABLE public.promocoes ALTER COLUMN prom_id SET GENERATED BY DEFAULT;
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.promocoes'::regclass AND contype = 'p') THEN
        ALTER TABLE public.promocoes ADD CONSTRAINT promocoes_pk PRIMARY KEY (prom_id);
    END IF;

    -- Mantém o próximo ID acima dos registros e do valor já consumido pela sequência.
    sequencia := pg_get_serial_sequence('public.promocoes', 'prom_id');
    SELECT max(prom_id) INTO maior_id FROM public.promocoes;
    IF maior_id IS NOT NULL OR ultimo_id IS NOT NULL THEN
        PERFORM setval(sequencia, GREATEST(maior_id, ultimo_id, pg_sequence_last_value(sequencia::regclass)), true);
    END IF;

    IF NOT EXISTS (SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.promocoes'::regclass AND conname = 'ck_promocoes_datas') THEN
        ALTER TABLE public.promocoes ADD CONSTRAINT ck_promocoes_datas
            CHECK (prom_data_maxima >= prom_data_minima);
    END IF;
END $$;

COMMIT;
