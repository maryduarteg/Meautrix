-- Associação de procedimentos às promoções.
-- Pode ser executado novamente: preserva vínculos existentes e ajusta a estrutura legada.
BEGIN;

CREATE TABLE IF NOT EXISTS public.promocoes_procedimentos (
    prom_proc_id INTEGER NOT NULL GENERATED BY DEFAULT AS IDENTITY
        (INCREMENT 1 START 1 MINVALUE 1 MAXVALUE 2147483647 CACHE 1),
    procedimentos_proc_id INTEGER NOT NULL,
    promocoes_prom_id INTEGER NOT NULL,
    prom_proc_desconto NUMERIC(10,2) NOT NULL,
    CONSTRAINT promocoes_procedimentos_pk PRIMARY KEY (prom_proc_id),
    CONSTRAINT prom_proc_unique UNIQUE (promocoes_prom_id, procedimentos_proc_id),
    CONSTRAINT procedimentos_fkv2 FOREIGN KEY (procedimentos_proc_id)
        REFERENCES public.procedimentos (proc_id) ON UPDATE NO ACTION ON DELETE CASCADE,
    CONSTRAINT promocoes_fk FOREIGN KEY (promocoes_prom_id)
        REFERENCES public.promocoes (prom_id) ON UPDATE NO ACTION ON DELETE CASCADE
);

ALTER TABLE public.promocoes_procedimentos
    ADD COLUMN IF NOT EXISTS prom_proc_desconto NUMERIC(10,2);

-- Registros legados não tinham desconto. Eles continuam válidos com desconto de R$ 0,00.
UPDATE public.promocoes_procedimentos
SET prom_proc_desconto = 0
WHERE prom_proc_desconto IS NULL;

ALTER TABLE public.promocoes_procedimentos
    ALTER COLUMN prom_proc_id SET NOT NULL,
    ALTER COLUMN procedimentos_proc_id SET NOT NULL,
    ALTER COLUMN promocoes_prom_id SET NOT NULL,
    ALTER COLUMN prom_proc_desconto TYPE NUMERIC(10,2),
    ALTER COLUMN prom_proc_desconto SET NOT NULL;

DO $$
DECLARE
    sequencia TEXT;
    maior_id INTEGER;
BEGIN
    IF EXISTS (
        SELECT 1
        FROM public.promocoes_procedimentos
        GROUP BY promocoes_prom_id, procedimentos_proc_id
        HAVING COUNT(*) > 1
    ) THEN
        RAISE EXCEPTION 'Existem procedimentos repetidos na mesma promoção. Corrija os vínculos antes de aplicar a restrição de unicidade.';
    END IF;

    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conrelid = 'public.promocoes_procedimentos'::regclass
          AND conname = 'prom_proc_unique'
    ) THEN
        ALTER TABLE public.promocoes_procedimentos
            ADD CONSTRAINT prom_proc_unique UNIQUE (promocoes_prom_id, procedimentos_proc_id);
    END IF;

    -- Recria as FKs com exclusão em cascata, caso a modelagem anterior exista.
    ALTER TABLE public.promocoes_procedimentos DROP CONSTRAINT IF EXISTS procedimentos_fkv2;
    ALTER TABLE public.promocoes_procedimentos DROP CONSTRAINT IF EXISTS promocoes_fk;
    ALTER TABLE public.promocoes_procedimentos
        ADD CONSTRAINT procedimentos_fkv2 FOREIGN KEY (procedimentos_proc_id)
            REFERENCES public.procedimentos (proc_id) ON UPDATE NO ACTION ON DELETE CASCADE;
    ALTER TABLE public.promocoes_procedimentos
        ADD CONSTRAINT promocoes_fk FOREIGN KEY (promocoes_prom_id)
            REFERENCES public.promocoes (prom_id) ON UPDATE NO ACTION ON DELETE CASCADE;

    -- Instala identidade para bancos legados que tinham somente uma coluna INTEGER.
    IF (SELECT attidentity FROM pg_attribute
        WHERE attrelid = 'public.promocoes_procedimentos'::regclass
          AND attname = 'prom_proc_id') = '' THEN
        ALTER TABLE public.promocoes_procedimentos ALTER COLUMN prom_proc_id DROP DEFAULT;
        ALTER TABLE public.promocoes_procedimentos ALTER COLUMN prom_proc_id
            ADD GENERATED BY DEFAULT AS IDENTITY;
    END IF;

    sequencia := pg_get_serial_sequence('public.promocoes_procedimentos', 'prom_proc_id');
    SELECT MAX(prom_proc_id) INTO maior_id FROM public.promocoes_procedimentos;
    IF maior_id IS NOT NULL THEN
        PERFORM setval(sequencia, maior_id, true);
    END IF;
END $$;

COMMIT;
